--Q1: Find the top 3 selling cities of each country.

WITH CitySales AS (
    SELECT L.Country, L.City, SUM(F.Sales) AS TotalSales
    FROM Fact F
    JOIN Location L ON F.[Location ID] = L.[Location ID]
    GROUP BY L.Country, L.City
)
SELECT Country, City, TotalSales
FROM (
    SELECT Country, City, TotalSales, 
           RANK() OVER (PARTITION BY Country ORDER BY TotalSales DESC) AS Rank
    FROM CitySales
) AS RankedCities
WHERE Rank <= 3;

select L.Country, L.City, SUM(F.Sales) as 'c1', DENSE_RANK() over(PARTITION by L.Country order by [Total Sales] desc)
from Fact F left join Location L on F.[Location ID]=L.[Location ID]
group by L.Country,L.City


--Q2: Find year-over-year percentage growth in sales.

SELECT YEAR(F.[Order Date]) AS Year,
       SUM(F.Sales) AS TotalSales,
       COALESCE(
           (SUM(F.Sales) - LAG(SUM(F.Sales)) OVER (ORDER BY YEAR(F.OrderDate))) * 100.0 / LAG(SUM(F.Sales)) OVER (ORDER BY YEAR(F.OrderDate)),
           0
       ) AS SalesGrowthPercentage
FROM Fact F
GROUP BY YEAR(F.[Order Date]);

--Q3: Find average city sales for each country.

SELECT L.Country, L.City, AVG(F.Sales) AS AvgCitySales
FROM Fact F
JOIN Location L ON F.[Location ID] = L.[Location ID]
GROUP BY L.Country, L.City;

--Q4: Find the number of countries where at least 5 cities have made sales more than 10000.
WITH CitySales AS(
    SELECT 
        L.Country, 
        L.City, 
        SUM(F.Sales) AS TotalSales
    FROM Fact F
    JOIN Location L ON F.[Location ID] = L.[Location ID]
    GROUP BY L.Country, L.City
),
CountryCityCount AS (
    SELECT 
        Country, 
        COUNT(City) AS CitiesWithSalesAbove10000
    FROM CitySales
    WHERE TotalSales > 10000
    GROUP BY Country
)
SELECT COUNT(Country) AS CountryCount
FROM CountryCityCount
WHERE CitiesWithSalesAbove10000 >= 5;



--Q5: Find the average order value of each customer.

SELECT F.[Customer ID], AVG(F.Sales) AS AvgOrderValue
FROM Fact F
GROUP BY F.[Customer ID]
ORDER BY AvgOrderValue

--Q6: Find the number of Indian customers who have produced an overall loss.
SELECT 
    COUNT(DISTINCT F.[Customer ID]) AS IndianCustomersWithLoss
FROM Fact F
JOIN Customer C ON F.[Customer ID] = C.[Customer ID]
JOIN Location L ON F.[Location ID] = L.[Location ID]
WHERE L.Country = 'India'
  AND F.Profit < 0;


--Q7: Find the top-selling sub-category in each segment.

SELECT C.Segment, P.[Sub-Category], SUM(F.Sales) AS TotalSales
FROM Fact F
JOIN Product P ON F.[Product ID] = P.[Product ID]
JOIN Customer C ON F.[Customer ID] = C.[Customer ID]
GROUP BY C.Segment, P.[Sub-Category]
ORDER BY C.Segment, P.[Sub-Category], TotalSales

--Q8: Find the quarter-over-quarter sales in India.

WITH QuarterlySales AS (
    SELECT 
        YEAR(F.[Order Date]) AS SalesYear,
        DATEPART(QUARTER, F.[Order Date]) AS SalesQuarter,
        SUM(F.Sales) AS TotalSales
    FROM Fact F
    JOIN Location L ON F.[Location ID] = L.[Location ID]
    WHERE L.Country = 'India'
    GROUP BY YEAR(F.[Order Date]), DATEPART(QUARTER, F.[Order Date])
),
QuarterlyGrowth AS (
    SELECT 
        SalesYear,
        SalesQuarter,
        TotalSales,
        LAG(TotalSales) OVER (ORDER BY SalesYear, SalesQuarter) AS PreviousQuarterSales
    FROM QuarterlySales
)
SELECT 
    SalesYear,
    SalesQuarter,
    TotalSales,
    (TotalSales - PreviousQuarterSales) * 100.0 / PreviousQuarterSales AS QoQGrowthPercentage
FROM QuarterlyGrowth


--Q9: Find the top 10 selling products in the current quarter.

WITH cte AS(
	SELECT P.[Product Name], SUM(F.Sales) [Total Sales], DENSE_RANK() OVER(ORDER BY SUM(F.Sales) DESC) rk
	FROM Fact F JOIN Product P ON F.[Product ID] = P.[Product ID]
	WHERE DATEPART(QUARTER, [Order Date]) = DATEPART(QUARTER, GETDATE())
	GROUP BY P.[Product Name]
)
SELECT [Product Name], [Total Sales]
FROM cte
WHERE rk <=10
ORDER BY [Total Sales] DESC


--Q10: Show segment-wise average profit per order.

